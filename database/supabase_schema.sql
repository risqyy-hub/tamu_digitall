-- -------------------------------------------------------------
--  USERS (akun admin & petugas)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama        VARCHAR(100) NOT NULL,
  username    VARCHAR(50)  NOT NULL,
  email       VARCHAR(100) DEFAULT NULL,
  telepon     VARCHAR(20)  DEFAULT NULL,
  password    VARCHAR(255) NOT NULL,
  role        VARCHAR(10)  NOT NULL DEFAULT 'petugas' CHECK (role IN ('admin','petugas')),
  foto        VARCHAR(255) DEFAULT NULL,
  status      VARCHAR(10)  NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','nonaktif')),
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username ON users (username);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email    ON users (email);

-- -------------------------------------------------------------
--  PARTNER_COMPANIES (perusahaan / instansi mitra)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS partner_companies (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_mitra      VARCHAR(30)  NOT NULL,
  nama_perusahaan VARCHAR(150) NOT NULL,
  alamat          TEXT         DEFAULT NULL,
  telepon         VARCHAR(20)  DEFAULT NULL,
  email           VARCHAR(100) DEFAULT NULL,
  pic_nama        VARCHAR(100) DEFAULT NULL,
  pic_telepon     VARCHAR(20)  DEFAULT NULL,
  status          VARCHAR(10)  NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','nonaktif')),
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_mitra_kode ON partner_companies (kode_mitra);
CREATE INDEX IF NOT EXISTS idx_mitra_nama ON partner_companies (nama_perusahaan);

-- -------------------------------------------------------------
--  VISITORS (identitas tamu)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS visitors (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_tamu       VARCHAR(30)  NOT NULL,
  nama            VARCHAR(100) NOT NULL,
  jenis_identitas VARCHAR(30)  NOT NULL DEFAULT 'KTP' CHECK (jenis_identitas IN ('KTP','SIM','Paspor','Kartu Pegawai','Lainnya')),
  no_identitas    VARCHAR(50)  DEFAULT NULL,
  telepon         VARCHAR(20)  DEFAULT NULL,
  email           VARCHAR(100) DEFAULT NULL,
  alamat          TEXT         DEFAULT NULL,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_visitors_kode      ON visitors (kode_tamu);
CREATE INDEX IF NOT EXISTS idx_visitors_nama      ON visitors (nama);
CREATE INDEX IF NOT EXISTS idx_visitors_identitas ON visitors (no_identitas);

-- -------------------------------------------------------------
--  REGISTERED_VISITORS (tamu terdaftar / pemilik QR)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS registered_visitors (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visitor_id     BIGINT NOT NULL REFERENCES visitors(id) ON DELETE CASCADE,
  mitra_id       BIGINT DEFAULT NULL REFERENCES partner_companies(id) ON DELETE SET NULL,
  no_kartu       VARCHAR(50) DEFAULT NULL,
  status         VARCHAR(10) NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','nonaktif')),
  registered_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_reg_no_kartu ON registered_visitors (no_kartu);
CREATE INDEX IF NOT EXISTS idx_reg_visitor ON registered_visitors (visitor_id);
CREATE INDEX IF NOT EXISTS idx_reg_mitra   ON registered_visitors (mitra_id);

-- -------------------------------------------------------------
--  VISITOR_QR_CODES (hanya hash SHA-256 token yang disimpan)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS visitor_qr_codes (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registered_visitor_id BIGINT NOT NULL REFERENCES registered_visitors(id) ON DELETE CASCADE,
  token_hash            CHAR(64) NOT NULL,
  status                VARCHAR(10) NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','dicabut')),
  valid_from            TIMESTAMPTZ NOT NULL,
  valid_until           TIMESTAMPTZ DEFAULT NULL,
  issued_by             BIGINT DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  revoked_at            TIMESTAMPTZ DEFAULT NULL,
  revoked_by            BIGINT DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_qr_token_hash ON visitor_qr_codes (token_hash);
CREATE INDEX IF NOT EXISTS idx_qr_registered ON visitor_qr_codes (registered_visitor_id);
CREATE INDEX IF NOT EXISTS idx_qr_status     ON visitor_qr_codes (status);

-- -------------------------------------------------------------
--  VISITS (check-in / check-out - setiap kedatangan = record baru)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS visits (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_kunjungan        VARCHAR(30)  NOT NULL,
  visitor_id            BIGINT NOT NULL REFERENCES visitors(id) ON DELETE RESTRICT,
  registered_visitor_id BIGINT DEFAULT NULL REFERENCES registered_visitors(id) ON DELETE SET NULL,
  mitra_id              BIGINT DEFAULT NULL REFERENCES partner_companies(id) ON DELETE SET NULL,
  qr_id                 BIGINT DEFAULT NULL REFERENCES visitor_qr_codes(id) ON DELETE SET NULL,
  instansi              VARCHAR(150) DEFAULT NULL,
  tujuan                VARCHAR(200) NOT NULL,
  pegawai_ditemui       VARCHAR(120) NOT NULL,
  keperluan             TEXT         DEFAULT NULL,
  hasil_kunjungan       TEXT         DEFAULT NULL,
  jam_masuk             TIMESTAMPTZ  NOT NULL DEFAULT now(),
  jam_keluar            TIMESTAMPTZ  DEFAULT NULL,
  durasi_menit          INT          DEFAULT NULL,
  status                VARCHAR(15)  NOT NULL DEFAULT 'berlangsung' CHECK (status IN ('berlangsung','selesai')),
  petugas_masuk_id      BIGINT DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  petugas_keluar_id     BIGINT DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_visits_kode   ON visits (kode_kunjungan);
CREATE INDEX IF NOT EXISTS idx_visits_visitor   ON visits (visitor_id);
CREATE INDEX IF NOT EXISTS idx_visits_registered ON visits (registered_visitor_id);
CREATE INDEX IF NOT EXISTS idx_visits_mitra     ON visits (mitra_id);
CREATE INDEX IF NOT EXISTS idx_visits_qr        ON visits (qr_id);
CREATE INDEX IF NOT EXISTS idx_visits_status    ON visits (status);
CREATE INDEX IF NOT EXISTS idx_visits_masuk     ON visits (jam_masuk);

-- -------------------------------------------------------------
--  GUARANTEES (jaminan - check-out ditolak selama masih 'aktif')
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS guarantees (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id          BIGINT NOT NULL REFERENCES visits(id) ON DELETE CASCADE,
  barang            VARCHAR(150) NOT NULL,
  jumlah            INT NOT NULL DEFAULT 1,
  keterangan        TEXT DEFAULT NULL,
  bukti_file        VARCHAR(255) DEFAULT NULL,
  status            VARCHAR(15) NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','dikembalikan')),
  diterima_oleh     BIGINT DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  dikembalikan_oleh BIGINT DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  diterima_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  dikembalikan_at   TIMESTAMPTZ DEFAULT NULL,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_guar_visit   ON guarantees (visit_id);
CREATE INDEX IF NOT EXISTS idx_guar_status  ON guarantees (status);

-- -------------------------------------------------------------
--  NOTIFICATIONS (user_id NULL = untuk semua pengguna)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS notifications (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT DEFAULT NULL REFERENCES users(id) ON DELETE CASCADE,
  judul      VARCHAR(150) NOT NULL,
  pesan      TEXT DEFAULT NULL,
  tipe       VARCHAR(10) NOT NULL DEFAULT 'info' CHECK (tipe IN ('info','success','warning','danger')),
  is_read    BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications (user_id, is_read);

-- -------------------------------------------------------------
--  ACTIVITY_LOGS (audit trail)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS activity_logs (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  username   VARCHAR(50) DEFAULT NULL,
  role       VARCHAR(10) DEFAULT NULL,
  aktivitas  VARCHAR(255) NOT NULL,
  ip_address VARCHAR(45) DEFAULT NULL,
  user_agent VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_logs_user    ON activity_logs (user_id);
CREATE INDEX IF NOT EXISTS idx_logs_created ON activity_logs (created_at);

-- -------------------------------------------------------------
--  SETTINGS (konfigurasi aplikasi key-value)
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS settings (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_name   VARCHAR(50) NOT NULL,
  value      TEXT DEFAULT NULL,
  deskripsi  VARCHAR(255) DEFAULT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_settings_key ON settings (key_name);

-- -------------------------------------------------------------
--  Trigger updated_at otomatis
-- -------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['users','partner_companies','visitors','registered_visitors',
                           'visitor_qr_codes','visits','guarantees','settings'] LOOP
    EXECUTE format(
      'DROP TRIGGER IF EXISTS trg_%s_updated ON %I;
       CREATE TRIGGER trg_%s_updated BEFORE UPDATE ON %I
       FOR EACH ROW EXECUTE FUNCTION set_updated_at();',
      t, t, t, t);
  END LOOP;
END $$;

